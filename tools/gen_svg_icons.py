"""Embeds Blender's icons (release/datafiles/icons_svg) for the kit.

    python tools/gen_svg_icons.py BLENDER_SOURCE_DIR

Reads source/blender/editors/include/UI_icons.hh for the icon names and
kinds (DEF_ICON / DEF_ICON_COLOR / DEF_ICON_OBJECT ...) and writes
kit/intern/kit_icons_svg.c: each SVG icon's name, kind and source, minus the
editor metadata. The kit rasterizes them with nanosvg the way Blender's
blf_glyph_cache_add_svg does, so icons are Blender's own.

Blender's icons are part of Blender (GPL-2.0-or-later).
SPDX-License-Identifier: GPL-2.0-or-later
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "kit", "intern", "kit_icons_svg.c")

# DEF_ICON_* macro -> tint (theme icon color class), as in interface_icons.cc
KINDS = {
    "DEF_ICON": 0, "DEF_ICON_COLOR": -1, "DEF_ICON_SCENE": 1, "DEF_ICON_COLLECTION": 2,
    "DEF_ICON_OBJECT": 3, "DEF_ICON_OBJECT_DATA": 4, "DEF_ICON_MODIFIER": 5,
    "DEF_ICON_SHADING": 6, "DEF_ICON_FOLDER": 7, "DEF_ICON_FUND": 8,
}


def minify(svg: str) -> str:
    svg = re.sub(r"\s+", " ", svg)  # one line: no raw newlines in the C strings
    svg = re.sub(r"<sodipodi:namedview.*?(/>|</sodipodi:namedview>)", "", svg, flags=re.S)
    svg = re.sub(r"<metadata.*?</metadata>", "", svg, flags=re.S)
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r"\s+(xmlns:(inkscape|sodipodi|rdf|cc|dc)|inkscape:[\w-]+|sodipodi:[\w-]+)=\"[^\"]*\"", "", svg)
    svg = re.sub(r">\s+<", "><", svg)
    return svg.strip()


def c_string(s: str) -> str:
    out = []
    for i in range(0, len(s), 100):
        part = s[i:i + 100].replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'"{part}"')
    return "\n    ".join(out)


def main() -> None:
    blender = sys.argv[1]
    header = open(os.path.join(blender, "source", "blender", "editors", "include", "UI_icons.hh"),
                  encoding="utf-8").read()
    svg_dir = os.path.join(blender, "release", "datafiles", "icons_svg")
    entries = []
    for macro, name in re.findall(r"^(DEF_ICON\w*)\((\w+)\)", header, flags=re.M):
        if macro not in KINDS:
            continue  # DEF_ICON_VECTOR, DEF_ICON_BLANK: drawn by code
        path = os.path.join(svg_dir, name.lower() + ".svg")
        if not os.path.exists(path):
            continue
        entries.append((name, KINDS[macro], minify(open(path, encoding="utf-8").read())))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/gen_svg_icons.py from Blender's icons_svg. Do not edit.\n"
                " * Blender's icons: GPL-2.0-or-later.\n"
                " * SPDX-License-Identifier: GPL-2.0-or-later */\n\n"
                '#include "kit_icons_svg.h"\n\n'
                "const BKSvgIcon bk_svg_icons[] = {\n")
        for name, kind, svg in entries:
            f.write(f'  {{"{name}", {kind},\n    {c_string(svg)}}},\n')
        f.write("};\n\n")
        f.write(f"const int bk_svg_icon_count = {len(entries)};\n")
    total = sum(len(s) for _, _, s in entries)
    print(f"wrote {OUT}: {len(entries)} icons, {total / 1048576:.2f} MB of SVG")


if __name__ == "__main__":
    main()
