def vector_name(inner: str) -> str:
    inner = inner.strip()
    n = inner.replace("const ", "").replace("*", "Ptr").replace(" ", "_")
    return "ImVector_" + n


def c_type(t: str, model: Model) -> str:
    """C++ type spelling -> C spelling (ImVector<T> -> ImVector_T); refs handled by callers."""
    m = re.search(r"ImVector<(.+)>", t)
    if m:
        t = t.replace(m.group(0), vector_name(m.group(1)))
    m = re.search(r"ImSmallStack_<\s*(\w+)\s*,\s*(\d+)\s*>", t)
    if m:
        t = t.replace(m.group(0), "ImSmallStack_%s_%s" % (m.group(1), m.group(2)))
    return t


def c_smallstacks(api):
    found = {}
    for s in api["structs"]:
        for fd in s["fields"]:
            if fd["type"] != "fnptr" and fd["type"] != "union":
                m = re.search(r"ImSmallStack_<\s*(\w+)\s*,\s*(\d+)\s*>", fd["type"])
                if m:
                    found["ImSmallStack_%s_%s" % (m.group(1), m.group(2))] = (m.group(1), int(m.group(2)))
    return found


def c_vectors(api, model):
    """All ImVector<T> instantiations used in fields and parameters."""
    found = {}

    def scan(t):
        for m in re.finditer(r"ImVector<([^>]+)>", t):
            found[vector_name(m.group(1))] = m.group(1).strip()
    for s in api["structs"]:
        for fd in s["fields"]:
            for g in (fd["union"] if fd["type"] == "union" else [fd]):
                if g["type"] != "fnptr":
                    scan(g["type"])
    for f in all_functions(api):
        scan(f["ret"])
        for a in f["args"]:
            if a["type"] != "fnptr":
                scan(a["type"])
    return found


def c_decl(t: str, name: str, model: Model, array=None) -> str:
    if t == "fnptr":
        raise ValueError
    s = c_type(t, model)
    sep = " "
    arr = ""
    if array is not None:
        arr = "".join("[%s]" % a for a in (array if isinstance(array, list) else [array]))
    return "%s%s%s%s" % (s, sep, name, arr)


def c_fnptr_decl(fp, name, model):
    args = ", ".join(c_param_decl(a, model) for a in fp["args"]) or "void"
    r = c_type(fp["ret"], model)
    return "%s (*%s)(%s)" % (r, name, args)


def c_param_type(a, model):
    """-> C parameter type for a C++ parameter (refs become pointers / values)."""
    t = a["type"]
    if t.endswith("&"):
        c = parse_ctype(t)
        if c["const"] and not c["ptr"] and (c["base"] in VALUE_STRUCTS or model.scalar_kind(c["base"])):
            return c["base"]
        return t[:-1] + "*"
    return t


def c_param_decl(a, model):
    if a["type"] == "fnptr":
        return c_fnptr_decl(a["fnptr"], a["name"], model)
    if a["type"] == "...":
        return "..."
    return c_decl(c_param_type(a, model), a["name"], model, a.get("array"))


def c_ret_type(f, model):
    t = f["ret"]
    if t.endswith("&"):
        return t[:-1] + "*"
    return t or "void"


def is_value_struct(base, model):
    return base in VALUE_STRUCTS


def cpp_qualify(t: str, model: Model) -> str:
    """Qualify imgui type names with :: (the C++ wrappers live in namespace cimgui)."""
    def q(m):
        w = m.group(0)
        if w in model.structs or w in model.opaque or w in model.typedefs or w in model.enum_types or w == "ImVector":
            return "::" + w
        return w
    return re.sub(r"(?<![:\w])[A-Za-z_]\w*", q, t)


def cpp_arg_expr(a, model):
    """C argument -> C++ argument expression."""
    t = a["type"]
    n = a["name"]
    if t == "fnptr":
        return "reinterpret_cast<%s>(%s)" % (cpp_fnptr_type(a["fnptr"], model), n)
    if t in ("...",):
        return None
    if a.get("array") is not None:
        c = parse_ctype(t)
        if model.is_struct(c["base"]) or c["base"] in model.enum_types:
            return "reinterpret_cast<%s*>(%s)" % (cpp_qualify(t, model), n)
        return n
    c = parse_ctype(t)
    base = c["base"]
    if t.endswith("&"):
        if c["const"] and not c["ptr"] and (base in VALUE_STRUCTS or model.scalar_kind(base)):
            if base in VALUE_STRUCTS:
                return "cimgui_cast<::%s>(%s)" % (base, n)
            return n
        inner = cpp_qualify(t[:-1], model)
        return "*reinterpret_cast<%s*>(%s)" % (inner, n)
    if c["ptr"]:
        if model.typedefs.get(base, {}).get("type") == "fnptr":
            return "reinterpret_cast<%s>(%s)" % (cpp_qualify(t, model), n)
        if model.is_struct(base) or base in model.enum_types or "ImVector" in base:
            return "reinterpret_cast<%s>(%s)" % (cpp_qualify(t, model), n)
        return n
    if base in VALUE_STRUCTS or base in model.structs:
        return "cimgui_cast<::%s>(%s)" % (base, n)
    if base in model.enum_types:
        return "(::%s)%s" % (base, n)
    if model.typedefs.get(base, {}).get("type") == "fnptr":
        return "reinterpret_cast<::%s>(%s)" % (base, n)
    return n


def cpp_fnptr_type(fp, model):
    args = ", ".join(cpp_qualify(c_param_type(a, model) if a["type"] != "fnptr" else "void*", model) + ("*" if a.get("array") is not None else "") for a in fp["args"])
    return "%s (*)(%s)" % (cpp_qualify(fp["ret"], model), args)


def cpp_ret_wrap(f, expr, model):
    t = f["ret"]
    if not t or t == "void":
        return expr + ";"
    c = parse_ctype(t)
    base = c["base"]
    if t.endswith("&"):
        if model.is_struct(base) or base in model.enum_types or "ImVector" in base:
            return "return reinterpret_cast<%s*>(&%s);" % (c_type(t[:-1], model).replace("ImVector", "cimgui::ImVector") if "ImVector" in t else ("const " if c["const"] else "") + "cimgui::" + base + "*" * len(c["ptr"]), expr)
        return "return &%s;" % expr
    if c["ptr"]:
        if model.is_struct(base) or base in model.enum_types:
            cq = ("const " if c["const"] else "") + "cimgui::" + base + "*" * len(c["ptr"])
            return "return reinterpret_cast<%s>(%s);" % (cq, expr)
        return "return %s;" % expr
    if base in VALUE_STRUCTS or base in model.structs:
        return "return cimgui_cast<cimgui::%s>(%s);" % (base, expr)
    if base in model.enum_types:
        return "return (cimgui::%s)%s;" % (base, expr)
    return "return %s;" % expr


def c_fields(s, model, indent="    "):
    lines = []
    for fd in s["fields"]:
        if fd["type"] == "union":
            lines.append(indent + "union {")
            for g in fd["union"]:
                lines.append(indent + "    " + c_field_decl(g, model) + ";")
            lines.append(indent + "};")
        else:
            lines.append(indent + c_field_decl(fd, model) + ";")
    return lines


def array_dims(fd, model):
    arr = fd.get("array")
    if arr is None:
        return []
    arr = arr if isinstance(arr, list) else [arr]
    return [eval_dim(a, model) for a in arr]


def eval_dim(expr, model):
    toks = [m.group(0) for m in TOKEN_RE.finditer(expr)]
    return eval_enum_expr(toks, model.api["enum_values"])


def c_field_decl(fd, model):
    if fd["type"] == "fnptr":
        return c_fnptr_decl(fd["fnptr"], fd["name"], model)
    s = c_type(fd["type"], model)
    dims = array_dims(fd, model)
    arr = "".join("[%d]" % d for d in dims)
    sep = " "
    bits = " : %d" % fd["bitfield"] if "bitfield" in fd else ""
    return "%s%s%s%s%s" % (s, sep, fd["name"], arr, bits)


def c_supported(f, model):
    """C can bind everything except a variadic without a V twin."""
    if f.get("variadic") and not f.get("vfunc"):
        return False
    return True


