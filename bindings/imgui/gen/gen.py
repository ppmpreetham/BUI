def main(argv):
    api = build_api()
    model = Model(api)
    api_out = {k: v for k, v in api.items() if k != "enum_values"}
    OUT_JSON.write_text(json.dumps(api_out, indent=1) + "\n", encoding="utf-8", newline="\n")
    emit_c(api, model)
    cov = {}
    if "--c-only" not in argv:
        import gen_python
        cov["python"] = gen_python.emit(api, model, sys.modules[__name__])
        if (HERE / "gen_rust.py").exists():
            import gen_rust
            cov["rust"] = gen_rust.emit(api, model, sys.modules[__name__])
    ns = [f for f in api["functions"] if not f["obsolete"]]
    meth = [f for s in api["structs"] for f in s["methods"] + s["ctors"] if not f["obsolete"]]
    cov["imgui"] = {"namespace_functions": len(ns), "methods_and_ctors": len(meth),
                    "enums": len(api["enums"]), "structs": len(api["structs"]) + len(api["opaque"])}
    cov["c"] = {"namespace_functions": sum(1 for f in ns if c_supported(f, model)),
                "methods_and_ctors": sum(1 for f in meth if c_supported(f, model)),
                "missing": [f["scope"] + "::" + f["name"] for f in ns + meth if not c_supported(f, model)]}
    OUT_COVERAGE.write_text(json.dumps(cov, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk != "missing"} for k, v in cov.items()}, indent=1))


if __name__ == "__main__":
    sys.path.insert(0, str(HERE))
    main(sys.argv[1:])
