BUILTIN_SCALARS = {
    "bool": "bool", "char": "i8", "signed char": "i8", "unsigned char": "u8", "short": "i16",
    "signed short": "i16", "unsigned short": "u16", "int": "i32", "signed int": "i32",
    "unsigned int": "u32", "long long": "i64", "signed long long": "i64",
    "unsigned long long": "u64", "float": "f32", "double": "f64", "size_t": "usize",
}
VALUE_STRUCTS = ("ImVec2", "ImVec4", "ImTextureRef", "ImColor")


class Model:
    def __init__(self, api):
        self.api = api
        self.typedefs = {t["name"]: t for t in api["typedefs"]}
        self.structs = {s["name"]: s for s in api["structs"]}
        self.opaque = set(api["opaque"])
        self.enums_named = {}
        for e in api["enums"]:
            if e["name"]:
                self.enums_named[e["name"]] = e
        # enums used as types: `enum ImGuiKey : int` and plain `enum ImTextureFormat`
        self.enum_types = {n for n, e in self.enums_named.items() if not n.endswith("_")}

    def is_struct(self, n):
        return n in self.structs or n in self.opaque

    def resolve(self, name):
        """typedef chain -> builtin scalar name, 'enum:<Name>', 'fnptr:<Name>', struct name, or None"""
        seen = 0
        while seen < 20:
            seen += 1
            if name in BUILTIN_SCALARS:
                return name
            if name in self.enum_types:
                e = self.enums_named[name]
                return e["underlying"] or "int"
            if name in self.typedefs:
                t = self.typedefs[name]
                if t["type"] == "fnptr":
                    return "fnptr"
                if "*" in t["type"] or "<" in t["type"]:
                    return t["type"]
                name = t["type"]
                continue
            return name
        return name

    def scalar_kind(self, name):
        r = self.resolve(name)
        return BUILTIN_SCALARS.get(r)


def parse_ctype(t: str):
    """'const char* const' -> dict(base, const, ptr (list of const flags per level), ref)"""
    ref = t.endswith("&")
    if ref:
        t = t[:-1]
    levels = []
    tmpl = ""
    if ">" in t:  # ImVector<ImFont*>*: stars inside the template belong to the base
        k = t.rindex(">") + 1
        tmpl, t = t[:k], t[k:]
    parts = re.split(r"(\*)", t)
    base = (tmpl + parts[0]).strip()
    rest = parts[1:]
    const = base.startswith("const ")
    if const:
        base = base[6:]
    for k in range(0, len(rest), 2):
        after = rest[k + 1].strip() if k + 1 < len(rest) else ""
        levels.append(after == "const")
    return {"base": base.strip(), "const": const, "ptr": levels, "ref": ref}


