def type_tag(t: str) -> str:
    c = parse_ctype(t)
    base = c["base"]
    tag = {"const char": "Str", "char": "Char", "void": "Ptr" if c["ptr"] else "", "int": "Int",
           "unsigned int": "UInt", "float": "Float", "double": "Double", "bool": "Bool",
           "ImGuiID": "ID", "ImU32": "U32"}.get(base)
    if base == "const char" or (base == "char" and c["const"]):
        tag = "Str"
    if tag is None:
        tag = re.sub(r"^Im(Gui)?", "", base) or base
        tag = tag[:1].upper() + tag[1:]
    if base == "char" and c["const"] and c["ptr"]:
        return "Str"
    if base == "void" and c["ptr"]:
        return "Ptr"
    if c["ptr"] and base not in ("void",) and not (base == "char" and c["const"]):
        tag += "Ptr"
    return tag


def arg_type_key(a):
    if a["type"] == "fnptr":
        return "Callback"
    t = a["type"]
    if a.get("array") is not None:
        t += "*"
    return type_tag(t)


def assign_names(api):
    """C names for every function: c_full (all args) and c_short (required args only)."""
    used = set()
    groups = {}
    for f in api["functions"]:
        prefix = "ImGui" if f["scope"] == "ImGui" else f["scope"]
        groups.setdefault((prefix, f["name"]), []).append(f)
    for s in api["structs"]:
        for f in s["methods"]:
            groups.setdefault((s["name"], f["name"]), []).append(f)
        for f in s["ctors"]:
            groups.setdefault((s["name"], "New"), []).append(f)
    for (prefix, name), fs in groups.items():
        live = [f for f in fs if not f["obsolete"]]
        first = live[0] if live else None
        for f in fs:
            if f["obsolete"]:
                continue
            base = "%s_%s" % (prefix, name)
            if f is not first:
                fa = first["args"]
                tags, extra = [], []
                for k, a in enumerate(f["args"]):
                    if a["type"] in ("...", "va_list"):
                        continue
                    if k >= len(fa):
                        extra.append(arg_type_key(a))
                    elif arg_type_key(fa[k]) != arg_type_key(a) or (a.get("array") is None) != (fa[k].get("array") is None):
                        tags.append(arg_type_key(a))
                tags += extra
                if not tags:
                    tags.append("Short" if len(f["args"]) < len(fa) else "Alt")
                cand = base + tags[0]
                k = 1
                while (cand in used or cand + "Ex" in used) and k < len(tags):
                    cand += tags[k]
                    k += 1
                while cand in used:
                    cand += "_"
                base = cand
            f["overload_base"] = "%s_%s" % (prefix, name)
            if f is not first:
                f["overload_of"] = first.get("c_full")
            has_default = any("default" in a for a in f["args"])
            if has_default:
                short = base
                full = base + "Ex"
                while full in used or short in used:
                    full += "_"
                    if short in used:
                        short += "_"
                f["c_short"], f["c_full"] = short, full
                used.update((short, full))
            else:
                while base in used:
                    base += "_"
                f["c_full"] = base
                used.add(base)
            f["c_base"] = base


def all_functions(api):
    for f in api["functions"]:
        yield f
    for s in api["structs"]:
        for f in s["ctors"]:
            yield f
        for f in s["methods"]:
            yield f


def find_vfunc(api, f):
    """The `...V` / `...v` twin of a variadic function."""
    if f["scope"] == "ImGui":
        cands = api["functions"]
    else:
        cands = next(s["methods"] for s in api["structs"] if s["name"] == f["scope"])
    want = [a["type"] for a in f["args"]]
    want = [("va_list" if t == "..." else t) for t in want]
    for g in cands:
        if g["name"] in (f["name"] + "V", f["name"] + "v") and [a["type"] for a in g["args"]] == want:
            return g
    return None


def snake(name: str) -> str:
    s = re.sub(r"([A-Z])to([A-Z])", r"\1_to_\2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = s.lower().replace("__", "_")
    return s


def build_api():
    api = parse_header(HEADER)
    for st in api["structs"]:
        if not st["ctors"] and st["name"] not in VALUE_STRUCTS:
            st["ctors"].append({"name": st["name"], "scope": st["name"], "ret": st["name"] + "*", "args": [],
                                "obsolete": False, "api": False, "const": False, "static": False,
                                "ctor": True, "implicit": True})
    assign_names(api)
    for f in all_functions(api):
        if f.get("variadic"):
            v = find_vfunc(api, f)
            if v is not None:
                f["vfunc"] = v["name"]
    # struct dependency order (by-value fields first)
    order, seen = [], set()
    structs = {s["name"]: s for s in api["structs"]}

    def deps(s):
        out = []
        for fd in s["fields"]:
            group = fd["union"] if fd["type"] == "union" else [fd]
            for g in group:
                if g["type"] == "fnptr":
                    continue
                c = parse_ctype(g["type"])
                if c["ptr"]:
                    continue
                base = c["base"]
                m = re.match(r"ImVector<(.+)>$", base)
                if m:
                    continue
                if base in structs:
                    out.append(base)
        return out

    def visit(n):
        if n in seen:
            return
        seen.add(n)
        for d in deps(structs[n]):
            visit(d)
        order.append(n)
    for s in api["structs"]:
        visit(s["name"])
    api["struct_order"] = order
    return api


