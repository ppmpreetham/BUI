#!/usr/bin/env python3
"""Generates the C, Python and Rust bindings of Dear ImGui from the vendored imgui.h.

    py -3 -I bindings/imgui/gen/gen.py          (from the repository root, stdlib only)

1. parses bindings/imgui/extern/imgui/imgui.h (functions in `namespace ImGui`, enums,
   typedefs, structs with their fields and methods) into gen/imgui_api.json;
2. from that JSON writes
   - bindings/imgui/c/cimgui.h, cimgui.cpp         the C API (cimgui / dear_bindings style)
   - bindings/python/src/buiimgui_gen.inc          the CPython extension's functions/types
   - bindings/rust/blenderui-imgui/src/sys.rs      plain-Rust FFI (no bindgen)
   - bindings/rust/blenderui-imgui/src/safe.rs     the safe Rust layer
   - gen/coverage.json                             what each language binds

Naming (C): ImGui::Button -> ImGui_Button; a method ImDrawList::AddLine -> ImDrawList_AddLine
(self first). Default arguments: ImGui_Button(label) takes the required arguments only,
ImGui_ButtonEx(label, size) all of them. Overloads: the first keeps the name, the others get
a suffix from the parameter types that differ (ImGui_PushIDInt, ImGui_MenuItemBoolPtr...).
`fmt, ...` functions forward to their `...V` twin; constructors are X_New(...) / X_Delete().

SPDX-License-Identifier: GPL-2.0-or-later
"""

