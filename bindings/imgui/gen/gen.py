def strip_comments(src: str) -> str:
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            out.append(src[i:j + 1])
            i = j + 1
        elif src.startswith("//", i):
            j = src.find("\n", i)
            i = n if j < 0 else j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            out.append("\n" * src.count("\n", i, j + 2))
            i = j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


OBSOLETE = "IMGUI_DISABLE_OBSOLETE_FUNCTIONS"


def eval_cond(kind: str, expr: str, defined: dict) -> tuple[bool, bool, bool]:
    """-> (value, obsolete region, obsolete region of the #else)"""
    expr = expr.strip()
    if kind in ("ifdef", "ifndef"):
        name = expr.split()[0]
        if name == OBSOLETE:  # the library is built with the obsolete API: true, but flagged
            return (kind == "ifndef", kind == "ifndef", kind == "ifdef")
        val = name in defined
        return (val if kind == "ifdef" else not val, False, False)
    obs = ("!defined(" + OBSOLETE in expr.replace(" ", ""))
    e = re.sub(r"defined\s*\(\s*(\w+)\s*\)|defined\s+(\w+)",
               lambda m: "1" if (m.group(1) or m.group(2)) in defined else "0", expr)
    e = e.replace("&&", " and ").replace("||", " or ")
    e = re.sub(r"!(?!=)", " not ", e)
    e = re.sub(r"\b[A-Za-z_]\w*\b", lambda m: m.group(0) if m.group(0) in ("and", "or", "not") else "0", e)
    try:
        val = bool(eval(e, {"__builtins__": {}}))
    except Exception:
        val = False
    return (val, obs and val, False)


def preprocess(src: str):
    """-> list of (line text, obsolete flag) for the active lines; #defines collected."""
    src = re.sub(r"\\\n", " ", src)
    defined: dict = {}
    defines: dict = {}
    stack: list = []
    out = []
    for line in src.split("\n"):
        s = line.strip()
        if s.startswith("#"):
            d = s[1:].strip()
            kw = d.split(None, 1)[0] if d else ""
            rest = d[len(kw):].strip()
            active = all(e["active"] for e in stack)
            if kw in ("if", "ifdef", "ifndef"):
                if active:
                    val, obs, else_obs = eval_cond(kw, rest, defined)
                else:
                    val, obs, else_obs = False, False, False
                stack.append(dict(active=val, taken=val or not active, obs=obs, else_obs=else_obs))
            elif kw == "elif":
                e = stack[-1]
                parent = all(x["active"] for x in stack[:-1])
                if e["taken"] or not parent:
                    e["active"] = False
                else:
                    val, obs, _ = eval_cond("if", rest, defined)
                    e["active"], e["obs"] = val, obs
                    e["taken"] = val
            elif kw == "else":
                e = stack[-1]
                parent = all(x["active"] for x in stack[:-1])
                e["active"] = parent and not e["taken"]
                e["obs"] = e["else_obs"]
                e["taken"] = True
            elif kw == "endif":
                stack.pop()
            elif kw == "define" and active:
                m = re.match(r"(\w+)(\s+(.*))?$", rest)
                if m:
                    defined[m.group(1)] = True
                    if not rest[len(m.group(1)):].startswith("("):
                        defines[m.group(1)] = (m.group(3) or "").strip()
            continue
        if all(e["active"] for e in stack):
            out.append((line, any(e["obs"] for e in stack)))
    return out, defines


TOKEN_RE = re.compile(r"""
    (?P<str>"(?:\\.|[^"\\])*") |
    (?P<chr>'(?:\\.|[^'\\])*') |
    (?P<num>0[xX][0-9a-fA-F]+[uUlL]* | (?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?[fFuUlL]*) |
    (?P<id>[A-Za-z_]\w*) |
    (?P<op>::|->|<<|>>|&&|\|\||==|!=|<=|>=|\.\.\.|[^\s])
""", re.X)

DROP_TOKENS = {"IM_NODEBUGSTEP", "IM_MSVC_RUNTIME_CHECKS_OFF", "IM_MSVC_RUNTIME_CHECKS_RESTORE", "IMGUI_IMPL_API"}


class Tok(str):
    obs: bool = False


def tokenize(lines) -> list:
    toks = []
    for text, obs in lines:
        for m in TOKEN_RE.finditer(text):
            t = Tok(m.group(0))
            t.obs = obs
            toks.append(t)
    # drop attribute macros: IM_FMTARGS(n), IM_FMTLIST(n), ...
    out, i = [], 0
    while i < len(toks):
        t = toks[i]
        if t in ("IM_FMTARGS", "IM_FMTLIST"):
            i += 4
            continue
        if t in DROP_TOKENS:
            i += 1
            continue
        out.append(t)
        i += 1
    return out


def match_close(toks, i, open_, close):
    depth = 0
    for j in range(i, len(toks)):
        if toks[j] == open_:
            depth += 1
        elif toks[j] == close:
            depth -= 1
            if depth == 0:
                return j
    raise ValueError("unbalanced " + open_)


def read_stmt(toks, i):
    """One declaration: -> (decl tokens, body tokens or None, next index)."""
    decl, depth = [], 0
    while i < len(toks):
        t = toks[i]
        if t in ("(", "["):
            depth += 1
        elif t in (")", "]"):
            depth -= 1
        elif t == ";" and depth == 0:
            return decl, None, i + 1
        elif t == "{" and depth == 0:
            j = match_close(toks, i, "{", "}")
            body = toks[i + 1:j]
            k = j + 1
            if decl and decl[0] == "namespace":
                return decl + ["{}"], body, k
            if decl and decl[0] in ("struct", "union", "enum") or (decl and decl[0] == "typedef"):
                # struct X { } [declarators] ;
                tail = []
                while k < len(toks) and toks[k] != ";":
                    tail.append(toks[k])
                    k += 1
                k += 1
                return decl + ["{}"] + tail, body, k
            if k < len(toks) and toks[k] == ";":
                k += 1
            return decl, body, k
        decl.append(t)
        i += 1
    return decl, None, i


def split_commas(toks):
    parts, cur, depth = [], [], 0
    for t in toks:
        if t in ("(", "[", "{", "<"):
            depth += 1
        elif t in (")", "]", "}", ">"):
            depth -= 1
        if t == "," and depth == 0:
            parts.append(cur)
            cur = []
        else:
            cur.append(t)
    if cur:
        parts.append(cur)
    return parts


def join_type(toks) -> str:
    s = ""
    for t in toks:
        if t in ("*", "&", ">", ","):
            s = s.rstrip() + t
        elif t == "<":
            s = s.rstrip() + t
        else:
            s += ("" if not s or s[-1] == "<" else " ") + t
    return s


def join_expr(toks) -> str:
    s = ""
    for t in toks:
        if t in (")", ",", "]") or s.endswith(("(", "[")) or not s:
            s += t
        elif t in ("(", "[") and s and (s[-1].isalnum() or s[-1] == "_"):
            s += t
        else:
            s += " " + t
    return s.replace(" ,", ",")


SKIP_STRUCTS = {"ImNewWrapper"}  # IM_NEW()'s placement-new tag: not API
QUALIFIERS = {"IMGUI_API", "inline", "static", "constexpr", "virtual", "explicit", "extern"}


def parse_fnptr(toks):
    """`ret ( * name ) ( args )` -> (name, {"ret":..., "args":[...]})"""
    p = toks.index("(")
    ret = join_type(toks[:p])
    q = match_close(toks, p, "(", ")")
    inner = toks[p + 1:q]
    name = inner[-1] if inner and inner[-1] not in ("*",) else ""
    a = q + 1
    b = match_close(toks, a, "(", ")")
    args = [parse_param(x, k) for k, x in enumerate(split_commas(toks[a + 1:b]))]
    return name, {"ret": ret, "args": args}


def parse_param(toks, index):
    if toks == ["..."]:
        return {"name": "...", "type": "..."}
    if toks == ["void"]:
        return None
    if "(" in toks and toks[toks.index("(") + 1] == "*":
        name, fp = parse_fnptr(toks)
        return {"name": name or "arg%d" % index, "type": "fnptr", "fnptr": fp}
    default = None
    depth = 0
    for k, t in enumerate(toks):
        if t in ("(", "[", "<"):
            depth += 1
        elif t in (")", "]", ">"):
            depth -= 1
        elif t == "=" and depth == 0:
            default = join_expr(toks[k + 1:])
            toks = toks[:k]
            break
    array = None
    if toks and toks[-1] == "]":
        o = toks.index("[")
        array = join_expr(toks[o + 1:-1])
        toks = toks[:o]
    builtin = {"int", "float", "double", "char", "bool", "short", "long", "unsigned", "signed", "void", "*", "&"}
    if len(toks) >= 2 and toks[-1] not in builtin and re.match(r"[A-Za-z_]\w*$", toks[-1]):
        name, ttoks = toks[-1], toks[:-1]
    else:
        name, ttoks = "arg%d" % index, toks
    p = {"name": name, "type": join_type(ttoks)}
    if array is not None:
        p["array"] = array
    if default is not None:
        p["default"] = default
    return p


def parse_function(decl, scope, struct_name=None):
    """decl tokens (no body) -> function dict or None."""
    if "operator" in decl or decl[0] == "template" or "~" in decl or decl[0] in ("friend", "typedef"):
        return None
    p = decl.index("(")
    head = [t for t in decl[:p] if t not in QUALIFIERS]
    is_static = "static" in decl[:p]
    is_api = "IMGUI_API" in decl[:p]
    if not head:
        return None
    name = head[-1]
    q = match_close(decl, p, "(", ")")
    tail = decl[q + 1:]
    if "=" in tail and tail[tail.index("=") + 1] in ("delete", "0"):
        return None
    params = []
    for k, ptoks in enumerate(split_commas(decl[p + 1:q])):
        pp = parse_param(ptoks, k)
        if pp:
            params.append(pp)
    f = {
        "name": name,
        "scope": scope,
        "ret": join_type(head[:-1]),
        "args": params,
        "obsolete": bool(decl[0].obs or (name and getattr(name, "obs", False))),
        "api": is_api,
    }
    if struct_name:
        f["const"] = bool(tail and tail[0] == "const")
        f["static"] = is_static
        if name == struct_name and not f["ret"]:
            f["ctor"] = True
            f["ret"] = struct_name + "*"
    if any(a["type"] == "..." for a in params):
        f["variadic"] = True
    if any(a["type"] == "va_list" for a in params):
        f["va_list"] = True
    return f


def parse_field_decl(decl, out, struct_name):
    obs = bool(decl[0].obs)
    if decl[0] in ("typedef", "friend", "template", "using") or "operator" in decl:
        return
    if "static" in decl[:3]:
        return
    if "(" in decl and decl[decl.index("(") + 1] == "*":
        name, fp = parse_fnptr(decl)
        out.append({"name": name, "type": "fnptr", "fnptr": fp, "obsolete": obs})
        return
    parts = split_commas(decl)
    first = parts[0]
    # type = tokens up to the declarator name
    def declarator(toks):
        bits = None
        if ":" in toks:
            c = toks.index(":")
            bits = int(toks[c + 1])
            toks = toks[:c]
        if "=" in toks:
            toks = toks[:toks.index("=")]
        arrays = []
        while toks and toks[-1] == "]":
            o = len(toks) - 1 - toks[::-1].index("[")
            arrays.insert(0, join_expr(toks[o + 1:-1]))
            toks = toks[:o]
        return toks, arrays, bits
    first = [t for t in first if t != "mutable"]
    toks, arrays, bits = declarator(first)
    name = toks[-1]
    base = toks[:-1]
    fields = [(name, join_type(base), arrays, bits)]
    base_no_ptr = [t for t in base if t not in ("*", "&")]
    for extra in parts[1:]:
        t2, arrays2, bits2 = declarator(extra)
        ptrs = [t for t in t2 if t == "*"]
        fields.append((t2[-1], join_type(base_no_ptr + ptrs), arrays2, bits2))
    for name, typ, arrays, bits in fields:
        f = {"name": name, "type": typ, "obsolete": obs}
        if arrays:
            f["array"] = arrays[0] if len(arrays) == 1 else arrays
        if bits is not None:
            f["bitfield"] = bits
        out.append(f)


def parse_struct_body(name, body, api):
    st = {"name": name, "fields": [], "methods": [], "ctors": [], "has_dtor": False, "opaque": False}
    i = 0
    anon = 0
    while i < len(body):
        decl, sub, i = read_stmt(body, i)
        if not decl:
            continue
        while len(decl) >= 2 and decl[0] in ("public", "private", "protected") and decl[1] == ":":
            decl = decl[2:]
        if decl[0] == "template":
            continue
        if decl[0] in ("struct", "union", "enum") and "{}" in decl:
            kind = decl[0]
            if kind == "union" and decl[1] == "{}":
                group = []
                for d2 in split_stmts(sub):
                    parse_field_decl(d2, group, name)
                st["fields"].append({"name": "__union%d" % anon, "type": "union", "union": group,
                                     "obsolete": bool(decl[0].obs)})
                anon += 1
            elif kind == "struct":
                nested = parse_struct_body(decl[1], sub, api)
                api["structs"].append(nested)
            elif kind == "enum":
                parse_enum(decl, sub, api)
            continue
        if decl[0] == "~" or (len(decl) > 1 and decl[1] == "~") or "~" in decl[:3]:
            st["has_dtor"] = True
            continue
        if "(" in decl and decl[decl.index("(") + 1] != "*" and ("[" not in decl or decl.index("(") < decl.index("[")):
            f = parse_function(decl, name, name)
            if f is None:
                continue
            if f.get("ctor"):
                st["ctors"].append(f)
            else:
                st["methods"].append(f)
            continue
        parse_field_decl(decl, st["fields"], name)
    return st


def split_stmts(body):
    i, out = 0, []
    while i < len(body):
        decl, _, i = read_stmt(body, i)
        if decl:
            out.append(decl)
    return out


def eval_enum_expr(expr_toks, values):
    e = []
    for t in expr_toks:
        if t in values:
            e.append(str(values[t]))
        elif re.match(r"^(0[xX][0-9a-fA-F]+|\d+)[uUlL]*$", t):
            e.append(re.sub(r"[uUlL]+$", "", t))
        elif t in ("|", "&", "<<", ">>", "~", "-", "+", "*", "(", ")", "^"):
            e.append(t)
        elif t == "/":
            e.append("//")
        elif t in ("int", "ImU8"):
            e.append("")  # casts
        else:
            raise ValueError("enum expr: %r" % (expr_toks,))
    return int(eval(" ".join(e), {"__builtins__": {}}))


def parse_enum(decl, body, api):
    name = decl[1] if len(decl) > 1 and decl[1] not in (":", "{}") else ""
    underlying = None
    if ":" in decl:
        c = decl.index(":")
        underlying = join_type(decl[c + 1:decl.index("{}")])
    values = []
    nxt = 0
    for part in split_commas(body):
        if not part:
            continue
        vname = part[0]
        if "=" in part:
            expr_toks = part[part.index("=") + 1:]
            val = eval_enum_expr(expr_toks, api["enum_values"])
            expr = join_expr(expr_toks)
        else:
            val, expr = nxt, None
        api["enum_values"][vname] = val
        nxt = val + 1
        v = {"name": vname, "value": val, "obsolete": bool(part[0].obs)}
        if expr is not None:
            v["expr"] = expr
        values.append(v)
    api["enums"].append({"name": name, "underlying": underlying, "values": values,
                         "flags": name.endswith("Flags_") or "Flags_" in name})


def parse_header(path: Path):
    src = strip_comments(path.read_text(encoding="utf-8"))
    lines, defines = preprocess(src)
    toks = tokenize(lines)
    api = {"version": None, "defines": {}, "typedefs": [], "enums": [], "structs": [], "opaque": [],
           "functions": [], "enum_values": {}}
    for k, v in defines.items():
        if re.match(r'^("[^"]*"|-?(0x[0-9A-Fa-f]+|\d+))$', v):
            api["defines"][k] = v
            if not v.startswith('"'):
                api["enum_values"][k] = int(v, 0)
    api["version"] = defines.get("IMGUI_VERSION", "").strip('"')
    declared, defined = [], set()

    def top(toks, i, end, ns=None):
        while i < end:
            if toks[i] == "}":
                i += 1
                continue
            start = i
            decl, body, i = read_stmt(toks, i)
            if not decl:
                continue
            if decl[0] == "namespace":
                top(body, 0, len(body), ns=decl[1])
                continue
            if decl[0] == "template":
                continue
            if decl[0] in ("struct", "union") and body is None and len(decl) == 2:
                declared.append(decl[1])
                continue
            if decl[0] == "struct" and body is not None:
                if decl[1] in SKIP_STRUCTS:
                    continue
                st = parse_struct_body(decl[1], body, api)
                api["structs"].append(st)
                defined.add(decl[1])
                continue
            if decl[0] == "enum":
                if body is not None:
                    parse_enum(decl, body, api)
                continue
            if decl[0] == "typedef":
                t = decl[1:]
                if "(" in t and t[t.index("(") + 1] == "*":
                    name, fp = parse_fnptr(t)
                    api["typedefs"].append({"name": name, "type": "fnptr", "fnptr": fp, "obsolete": bool(decl[0].obs)})
                else:
                    api["typedefs"].append({"name": t[-1], "type": join_type(t[:-1]), "obsolete": bool(decl[0].obs)})
                continue
            if ns == "ImGui" and body is None and "(" in decl:
                f = parse_function(decl, "ImGui")
                if f:
                    api["functions"].append(f)
                continue
            # anything else (inline definitions out of class, using...) is skipped
        return i

    top(toks, 0, len(toks))
    for name in declared:
        if name not in defined and name not in api["opaque"]:
            api["opaque"].append(name)
    return api


