# structs without a declared constructor that still get X_New (value-initialized)
DEFAULT_NEW = set()


def nreq(f):
    n = 0
    for a in f["args"]:
        if "default" in a or a["type"] == "...":
            break
        n += 1
    return n


def c_variants(f):
    """(C name, number of C++ args passed) for each emitted C function."""
    total = len([a for a in f["args"] if a["type"] != "..."])
    if f.get("c_short"):
        return [(f["c_short"], nreq(f)), (f["c_full"], total)]
    return [(f["c_full"], total)]


def c_proto(f, cname, nargs, model):
    params = []
    if f["scope"] != "ImGui" and not f.get("static") and not f.get("ctor"):
        params.append("%s%s* self" % ("const " if f.get("const") else "", f["scope"]))
    args = [a for a in f["args"] if a["type"] != "..."][:nargs]
    params += [c_param_decl(a, model) for a in args]
    if f.get("variadic"):
        params.append("...")
    ret = c_ret_type(f, model)
    return "%s %s(%s)" % (c_type(ret, model), cname, ", ".join(params) or "void")


def c_body(f, nargs, model):
    args = [a for a in f["args"] if a["type"] != "..."][:nargs]
    exprs = [cpp_arg_expr(a, model) for a in args]
    if f["scope"] == "ImGui":
        callee = "ImGui::"
    elif f.get("ctor"):
        callee = None
    elif f.get("static"):
        callee = "::%s::" % f["scope"]
    else:
        callee = "reinterpret_cast<%s::%s*>(self)->" % ("const " if f.get("const") else "", f["scope"])
    if f.get("ctor"):
        return ["return reinterpret_cast<cimgui::%s*>(IM_NEW(::%s)(%s));" % (f["scope"], f["scope"], ", ".join(exprs))]
    if f.get("variadic"):
        last = args[-1]["name"]
        call = "%s%s(%s)" % (callee, f["vfunc"], ", ".join(exprs + ["args"]))
        out = ["va_list args;", "va_start(args, %s);" % last]
        if f["ret"] and f["ret"] != "void":
            out.append("auto ret = %s;" % call)
            out.append("va_end(args);")
            out.append(cpp_ret_wrap(f, "ret", model))
        else:
            out.append(call + ";")
            out.append("va_end(args);")
        return out
    call = "%s%s(%s)" % (callee, f["name"], ", ".join(exprs))
    return [cpp_ret_wrap(f, call, model)]


